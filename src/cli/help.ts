import { GROUPS, type Command, type Option } from './command.ts';

// Help for people at a terminal, and the same text as Markdown for docs/cli.md. Both come from the commands'
// declarations.

export const TAGLINE = 'Build a product from a spec with headless coding agents, in a loop you steer.';

export const GLOBAL_OPTIONS: Record<string, Option> = {
  root: { type: 'string', value: 'dir', description: 'The project to act on. By default, the nearest folder up from here with a .helix/ folder, or $HELIX_PROJECT.' },
  json: { type: 'boolean', description: 'Machine-readable output, for commands that list or show something.' },
  help: { type: 'boolean', short: 'h', description: 'Show help for helix-loop or for one command.' },
  version: { type: 'boolean', short: 'v', description: 'Show the version.' },
};

const flag = (name: string, o: Option) => `${o.short ? `-${o.short}, ` : ''}--${name}${o.type === 'string' ? ` <${o.value ?? 'value'}>` : ''}`;
export const usageLine = (c: Command) =>
  ['helix-loop', c.name, ...(c.args ?? []).map((a) => (a.optional ? `[${a.name}${a.variadic ? '...' : ''}]` : `<${a.name}${a.variadic ? '...' : ''}>`)), ...(Object.keys(c.options ?? {}).length || c.json ? ['[options]'] : [])].join(' ');

function columns(rows: [string, string][], indent = 2, fixed?: number): string[] {
  const width = fixed ?? Math.min(30, Math.max(...rows.map(([a]) => a.length)) + 2);
  return rows.map(([a, b]) => `${' '.repeat(indent)}${a.length >= width ? `${a}\n${' '.repeat(indent + width)}` : a.padEnd(width)}${b}`);
}

export function overview(commands: Command[], version: string): string {
  const out = [`helix-loop ${version}: ${TAGLINE}`, '', 'Usage: helix-loop <command> [options]', ''];
  // One column width for every group, so the summaries line up down the page.
  const width = Math.max(...commands.filter((c) => !c.hidden).map((c) => c.name.length), ...Object.entries(GLOBAL_OPTIONS).map(([n, o]) => flag(n, o).length)) + 2;
  for (const g of GROUPS) {
    const mine = commands.filter((c) => c.group === g && !c.hidden);
    if (!mine.length) continue;
    out.push(g, ...columns(mine.map((c) => [c.name, c.summary]), 2, width), '');
  }
  out.push('Options for every command', ...columns(Object.entries(GLOBAL_OPTIONS).map(([n, o]) => [flag(n, o), o.description]), 2, width), '');
  out.push('Run `helix-loop <command> --help` for a command\'s options and examples.');
  out.push('The full reference is docs/cli.md; the concepts are in docs/concepts.md.');
  return out.join('\n');
}

export function commandHelp(c: Command): string {
  const out = [`${usageLine(c)}`, '', c.summary];
  if (c.description) out.push('', c.description.trim());
  if (c.args?.length) out.push('', 'Arguments', ...columns(c.args.map((a) => [a.name, `${a.description}${a.optional ? ' (optional)' : ''}`])));
  const opts = Object.entries(c.options ?? {});
  if (opts.length || c.json) out.push('', 'Options', ...columns([...opts.map(([n, o]): [string, string] => [flag(n, o), o.description]), ...(c.json ? [[flag('json', GLOBAL_OPTIONS.json!), GLOBAL_OPTIONS.json!.description] as [string, string]] : [])]));
  if (c.examples?.length) out.push('', 'Examples', ...c.examples.flatMap(([cmd, what]) => [`  ${cmd}`, `      ${what}`]));
  if (c.project !== false) out.push('', 'Acts on the project around the current folder, or the one --root names.');
  return out.join('\n');
}

// docs/cli.md: generated by `helix-loop docs`, checked by the tests to match the commands.
export function referenceMarkdown(commands: Command[]): string {
  const out = [
    '# CLI reference',
    '',
    '<!-- Generated by `helix-loop docs` from the commands themselves. Do not edit by hand. -->',
    '',
    TAGLINE,
    'Every command also answers `--help`.',
    '',
    'Commands act on the project around the current folder: the nearest folder up with a `.helix/` folder.',
    '`--root <dir>` or `$HELIX_PROJECT` names another.',
    '',
    '## Options for every command',
    '',
    '| Option | What it does |',
    '| --- | --- |',
    ...Object.entries(GLOBAL_OPTIONS).map(([n, o]) => `| \`${flag(n, o)}\` | ${o.description} |`),
    '',
  ];
  out.push('## Commands', '');
  for (const g of GROUPS) {
    const mine = commands.filter((c) => c.group === g && !c.hidden);
    if (!mine.length) continue;
    out.push(`- **${g}:** ${mine.map((c) => `[\`${c.name}\`](#${anchor(c.name)})`).join(', ')}`);
  }
  out.push('');
  for (const g of GROUPS) {
    const mine = commands.filter((c) => c.group === g && !c.hidden);
    if (!mine.length) continue;
    out.push(`## ${g}`, '');
    for (const c of mine) {
      out.push(`### helix-loop ${c.name}`, '', c.summary, '', '```', usageLine(c), '```', '');
      if (c.description) out.push(c.description.trim(), '');
      if (c.args?.length) out.push('| Argument | What it is |', '| --- | --- |', ...c.args.map((a) => `| \`${a.name}\` | ${a.description}${a.optional ? ' (optional)' : ''} |`), '');
      const opts = Object.entries(c.options ?? {});
      if (opts.length || c.json) {
        out.push('| Option | What it does |', '| --- | --- |', ...opts.map(([n, o]) => `| \`${flag(n, o)}\` | ${o.description} |`));
        if (c.json) out.push(`| \`--json\` | ${GLOBAL_OPTIONS.json!.description} |`);
        out.push('');
      }
      if (c.examples?.length) out.push('Examples:', '', '```sh', ...c.examples.flatMap(([cmd, what]) => [`# ${what}`, cmd]), '```', '');
    }
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

const anchor = (name: string) => `helix-loop-${name.replace(/\s+/g, '-')}`;
